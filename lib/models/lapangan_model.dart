/// Model sederhana untuk data lapangan.
class Lapangan {
  final String nama;
  final String lokasi;
  final double rating;
  final String gambar;
  final String harga;

  Lapangan({
    required this.nama,
    required this.lokasi,
    required this.rating,
    required this.gambar,
    required this.harga,
  });
}
